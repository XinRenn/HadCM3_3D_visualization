#!/usr/bin/env python3
"""Assemble v3/HadCM3_3D.html, the 3D walkthrough.

Inputs
  v3/src/page.html        page skeleton with @@CSS@@, @@CONTENT@@ and @@APP@@ placeholders
  v3/src/app.css          styles
  v3/src/app.js           the 3D application (ES module, three.js from jsDelivr)
  ../HadCM3_timestep_walkthrough_{en,zh}.html   step cards (STEPS) and parameter tables (MODS)
  ../v2/src/hadcm3_net.js                       per-component process networks (NETS, bilingual)

The field data are not inlined: the page loads data/hadcm3_state.js (made by build_data.py)
with a plain script tag, so it works from disk and when published with that file beside it.

Run: python3 v3/build_v3.py               -> v3/HadCM3_3D.html (language follows the browser, toggle in the header)
                                             and v3/HadCM3_3D_zh.html (opens in Chinese); full documents,
                                             for opening from disk
     python3 v3/build_v3.py --bare F      -> also F, the first page without the doctype/charset/viewport lines,
                                             for publishing as an Artifact (the host adds its own skeleton)
     python3 v3/build_v3.py --bare-zh F   -> the same for the Chinese page
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def read(*p):
    with open(os.path.join(*p), encoding='utf-8') as f:
        return f.read()


def slice_const(src, name):
    """Source text of `const NAME = [ ... ];` (the closing `  ];` sits on its own line)."""
    m = re.search(r'^  const %s = \[\n' % name, src, re.M)
    if not m:
        raise SystemExit('const %s not found' % name)
    end = src.index('\n  ];\n', m.start())
    return src[m.start():end + len('\n  ];')]


def v1_block(lang):
    src = read(ROOT, 'HadCM3_timestep_walkthrough_%s.html' % lang)
    parts = [
        "  const ALL = ['sun','rad','dyn','moist','bl','eng','gwd','cpl','land','veg','ice','ocn'];",
        "  const ATMOS = ['dyn','rad','moist','bl','eng','gwd','land'];",
        slice_const(src, 'STEPS'),
        slice_const(src, 'MODS'),
        '  return { STEPS, MODS };',
    ]
    return '(function () {\n' + '\n'.join(parts) + '\n})()'


def main():
    page = read(HERE, 'src', 'page.html')
    css = read(HERE, 'src', 'app.css')
    app = read(HERE, 'src', 'app.js')
    net = read(ROOT, 'v2', 'src', 'hadcm3_net.js')
    content = ('/* v1 step cards and parameter tables, v2 process networks (generated by build_v3.py) */\n'
               'window.HAD_V1 = { en: %s, zh: %s };\n' % (v1_block('en'), v1_block('zh')) + net)
    out = page.replace('@@CSS@@', css).replace('@@CONTENT@@', content).replace('@@APP@@', app)
    # Chinese page: fixed start language, Chinese title, description and loading line
    zh = (out.replace('@@LANGBOOT@@', "<script>window.HAD3D_LANG = 'zh';</script>\n")
             .replace('<title>HadCM3 in 3D</title>', '<title>HadCM3 三维</title>')
             .replace(re.search(r'<meta name="description" content="[^"]*">', out).group(0),
                      '<meta name="description" content="HadCM3（UM vn4.5）在三维地球上走完一个耦合日：'
                      '各子程序按调用顺序作用在模式自己的网格上，场取自工业革命前启动 dump。">')
             .replace('Loading HadCM3 fields…', '正在载入 HadCM3 场…'))
    out = out.replace('@@LANGBOOT@@', '')
    head = ('<!doctype html>\n<html lang="%s">\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n')
    targets = [(os.path.join(HERE, 'HadCM3_3D.html'), head % 'en' + out),
               (os.path.join(HERE, 'HadCM3_3D_zh.html'), head % 'zh-CN' + zh)]
    for flag, text in (('--bare', out), ('--bare-zh', zh)):
        if flag in sys.argv:
            targets.append((sys.argv[sys.argv.index(flag) + 1], text))
    for dst, text in targets:
        with open(dst, 'w', encoding='utf-8') as f:
            f.write(text)
        print('wrote %s (%.0f kB)' % (dst, len(text.encode()) / 1024))

if __name__ == '__main__':
    main()
